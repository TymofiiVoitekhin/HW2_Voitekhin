# ── 2. RAG Інструмент ──────────────────────────────────────────────────

@tool
def search_knowledge(query: str) -> str:
    """Пошук інформації у базі знань.
    
    Використовуйте цей інструмент, коли потрібна довідкова
    інформація, факти, правила налаштування або специфікації компонентів (наприклад, 
    умови замовлення, налаштування CAN, Starlink, логічні рівні).
    НЕ використовуйте для перевірки залишків на складі чи виконання дій (замовлення, прошивки).
    
    Args:
        query: Пошуковий запит (наприклад, "моделі Starlink", "умови постачання Makerfabs").
        
    Returns:
        Топ-3 релевантних документи з бази знань.
    """
    results = knowledge_base.query(query_texts=[query], n_results=3)
    
    if not results['documents'] or not results['documents'][0]:
        return "У базі знань немає релевантної інформації."
        
    docs = results['documents'][0]
    return '\n---\n'.join(docs)

